# Human-readable Japanese labels for each category. Used in both the
# system prompt (so Kayo offers them by name) and the dashboard.
CATEGORY_LABELS_JP: dict[str, str] = {
    "animals": "動物",
    "geography": "日本の地理",
    "showa": "昭和の歌・芸能",
    "seasons": "季節・行事",
    "cooking": "食べ物・料理",
    "history": "日本史",
    "kanji": "漢字読み",
    "proverbs": "ことわざ・慣用句",
    "mixed": "ミックス",
}


def pick_questions(category: str, n: int = 5, exclude_ids: set[int] | None = None) -> list[QuizItem]:
    """Pick `n` quiz items from a category (or mixed). `exclude_ids` is a
    set of (category, index) the user has already seen this month; pass it
    to avoid repeats. We don't track per-user state here — that lives in
    the activity scoring layer."""
    if category == "mixed":
        pool: list[QuizItem] = []
        for items in QUIZ_BANKS.values():
            pool.extend(items)
    else:
        pool = QUIZ_BANKS.get(category, [])
    if not pool:
        return []
    return random.sample(pool, min(n, len(pool)))


def category_list_for_prompt() -> str:
    """Format the category list as a comma-separated phrase for Kayo's
    spoken offer ("動物、日本の地理、…、それともミックス？")."""
    labels = [v for k, v in CATEGORY_LABELS_JP.items() if k != "mixed"]
    return "、".join(labels) + "、それともミックスでバラバラ"
